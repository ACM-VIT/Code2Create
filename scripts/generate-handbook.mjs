import { readFile, readdir, writeFile } from 'node:fs/promises'
import { resolve } from 'node:path'

const repositoryRoot = resolve(import.meta.dirname, '..')
const specsDirectory = resolve(repositoryRoot, 'specs')
const generatedFile = resolve(repositoryRoot, 'apps/backend/convex/generatedHandbook.ts')

const specFiles = (await readdir(specsDirectory))
  .filter((name) => /^\d{2}-.+\.md$/u.test(name))
  .sort()
const sources = ['README.md', ...specFiles.map((name) => `specs/${name}`)]

const documents = await Promise.all(
  sources.map(async (sourcePath, index) => {
    const markdown = await readFile(resolve(repositoryRoot, sourcePath), 'utf8')
    const heading = markdown.match(/^#\s+(.+)$/mu)?.[1]?.trim()
    const fallback = sourcePath.split('/').at(-1)?.replace(/\.md$/u, '').replaceAll('-', ' ')
    return {
      slug: index === 0 ? 'start-here' : sourcePath.split('/').at(-1)?.replace(/\.md$/u, '') ?? `document-${index}`,
      title: heading || fallback || `Document ${index}`,
      sourcePath,
      order: index,
      markdown,
    }
  }),
)

const output = `// Generated from README.md and specs/*.md by scripts/generate-handbook.mjs.\n` +
  `// Do not edit this file directly.\n\n` +
  `export const generatedHandbookDocuments = ${JSON.stringify(documents, null, 2)} as const;\n`

let current = ''
try {
  current = await readFile(generatedFile, 'utf8')
} catch {
  // The first generation creates the module.
}
if (current !== output) await writeFile(generatedFile, output)
