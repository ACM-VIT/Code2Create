const GlyphIn: React.FC<{ glyph: Glyph; i: number; start: number }> = ({ glyph, i, start }) => {
  const frame = useCurrentFrame();
  const { fps } = useVideoConfig();
  const delay = start + i * 3;

  if (glyph.kind === "flower") {
    const pop = interpolate(frame, [delay, delay + 24], [0, 1], {
      easing: Easing.bezier(0.34, 1.56, 0.64, 1),
      ...CLAMP,
    });
    const opacity = interpolate(frame, [delay, delay + 8], [0, 1], CLAMP);
    return (
      <g
        style={{
          opacity,
          transform: `scale(${interpolate(pop, [0, 1], [0.45, 1])}) rotate(${interpolate(pop, [0, 1], [-50, 0])}deg)`,
          transformBox: "fill-box",
          transformOrigin: "center",
        }}
      >
        {glyph.paths.map((d, pi) => (
          <path key={pi} d={d} fill={glyph.fill} />
        ))}
      </g>
    );
  }

  const raw = spring({
    frame,
    fps,
    delay: glyph.kind === "swirl" ? delay + 6 : delay,
    config: { damping: 200 },
  });
  const p = interpolate(raw, [0, 0.95], [0, 1], CLAMP);
  const y = interpolate(p, [0, 1], [26, 0]);
  const x = glyph.kind === "swirl" ? interpolate(p, [0, 1], [-24, 0]) : 0;
  return (
    <g
      style={{
        opacity: p,
        transform: `translate(${x}px, ${y}px)`,
        filter: `blur(${interpolate(p, [0, 1], [8, 0])}px)`,
      }}
    >
      {glyph.paths.map((d, pi) => (
        <path key={pi} d={d} fill={glyph.fill} />
      ))}
    </g>
  );
};

export const Wordmark: React.FC<{ start: number; width: number; sheen?: number }> = ({
  start,
  width,
  sheen,
}) => {
  const sheenActive = sheen !== undefined && sheen > -1 && sheen < 2;
  const sheenX = (sheen ?? 0) * 0.6 * 1032;
  return (
    <svg viewBox="0 0 1032 131" style={{ width, overflow: "visible" }}>
      {GLYPHS.map((glyph, i) => (
        <GlyphIn key={i} glyph={glyph} i={i} start={start} />
      ))}
      {sheenActive ? (
        <>
          <defs>
            <linearGradient
              id="wm-sheen"
              gradientUnits="userSpaceOnUse"
              x1={sheenX - 186}
              y1={15}
              x2={sheenX + 186}
              y2={116}
            >
              <stop offset="0" stopColor="#fff" stopOpacity="0" />
              <stop offset="0.5" stopColor="#fff" stopOpacity="1" />
              <stop offset="1" stopColor="#fff" stopOpacity="0" />
            </linearGradient>
            <mask id="wm-sheen-mask">
              <rect x={-200} y={-60} width={1432} height={260} fill="url(#wm-sheen)" />
            </mask>
          </defs>
          <g
            mask="url(#wm-sheen-mask)"
            opacity={0.8}
            style={{ filter: "drop-shadow(0 0 18px rgba(241, 206, 223, 0.9))" }}
          >
            {GLYPHS.flatMap((glyph) => glyph.paths).map((d, i) => (
              <path key={i} d={d} fill="#FFF0F5" />
            ))}
          </g>
        </>
      ) : null}
    </svg>
  );
};
